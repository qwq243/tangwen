# 空表的豁免名单：目前是空的 —— 44 卷都有人可写（连《熵增》那串温度数字和《疯人院》
# 的童谣都写了「材料没写性别的那个人 / 只收女人和小孩」）。留着是为了以后真有
# 完全没有人物的卷时，能显式声明「空表是结论」而不是被当成漏写。
NO_PEOPLE_OK: dict[str, str] = {}


def text_of(puzzle: dict) -> str:
    return puzzle["surface"] + "\n" + puzzle["bottom"]


def check(bundle: dict) -> tuple[list[str], list[str], list[str]]:
    """返回 (错, 警告, 汇总行)。错 = 必须修；警告 = 复看。"""
    by_id = {p["id"]: p for p in bundle["puzzles"]}
    errs: list[str] = []
    warns: list[str] = []
    for pid in by_id:
        if pid not in CAST and pid not in NO_PEOPLE_OK:
            errs.append(f"{pid}: 缺人物表")
    for pid, rows in CAST.items():
        p = by_id.get(pid)
        if not p:
            errs.append(f"{pid}: 卷宗里没有这一卷")
            continue
        body = text_of(p)
        names = set()
        for r in rows:
            name = (r.get("name") or "").strip()
            if not name:
                errs.append(f"{pid}: 有一条没写 name")
                continue
            if name in names:
                errs.append(f"{pid}: 人物表里 {name} 重复")
            names.add(name)
            if not (r.get("who") or "").strip():
                errs.append(f"{pid}/{name}: 缺 who")
            sex = (r.get("sex") or "").strip()
            if not sex:
                errs.append(f"{pid}/{name}: 缺 sex")
                continue
            ev = (r.get("ev") or "").strip()
            if sex in SEX_FIXED:
                if not ev:
                    errs.append(f"{pid}/{name}: 写了「{sex}」却没给证据 ev")
                elif ev not in body:
                    errs.append(f"{pid}/{name}: 证据不在正文里 → 《{ev}》")
            elif sex == UNSTATED:
                pass
            elif not ev:
                errs.append(f"{pid}/{name}: 跨阶段性别「{sex}」也要给证据 ev")
            elif ev not in body:
                errs.append(f"{pid}/{name}: 证据不在正文里 → 《{ev}》")
        # 覆盖检查比逐条刷屏有用：正文里有男性线索、表里却一条「男」都没有，才是真缺口
        sexes = " ".join((r.get("sex") or "") for r in rows)
        if MALE_CUE.search(body) and "男" not in sexes and pid not in CUE_EXCUSE:
            warns.append(f"{pid}: 正文有男性线索（他/男人/哥哥…），人物表里却没有一条「男」—— 复看")
        if FEMALE_CUE.search(body) and "女" not in sexes and pid not in CUE_EXCUSE:
            warns.append(f"{pid}: 正文有女性线索（她/女人/妹妹…），人物表里却没有一条「女」—— 复看")
    return errs, warns, []


def apply_cast(bundle: dict) -> int:
    """把 cast 插到 facts 后面（挨着它补的那块数据），返回改动卷数。"""
    changed = 0
    for p in bundle["puzzles"]:
        rows = CAST.get(p["id"], [])
        want = [{"name": r["name"], "sex": r["sex"], "who": r["who"]} for r in rows]
        if p.get("cast") == want:
            continue
        # 重建字段顺序：id … facts, cast, keys …
        out = {}
        for k, v in p.items():
            if k == "cast":
                continue
            out[k] = v
            if k == "facts":
                out["cast"] = want
        if "cast" not in out:
            out["cast"] = want
        p.clear()
        p.update(out)
        changed += 1
    return changed


def main() -> int:
    write = "--write" in sys.argv
    bundle = json.loads(PUZZLES.read_text(encoding="utf-8"))
    errs, warns, _ = check(bundle)

    total = sum(len(v) for v in CAST.values())
    stated = sum(1 for v in CAST.values() for r in v if r["sex"] in SEX_FIXED)
    special = sum(1 for v in CAST.values() for r in v if r["sex"] not in SEX_FIXED + (UNSTATED,))
    unstated = total - stated - special
    print(f"人物表 {len(CAST)} 卷 / {total} 条：写明男或女 {stated}，未写明 {unstated}，跨阶段 {special}")
    print()
    print(f"{'id':<14}{'条':>3}  人物（性别）")
    for p in bundle["puzzles"]:
        rows = CAST.get(p["id"], [])
        brief = "  ".join(f"{r['name']}={r['sex']}" for r in rows) or "（无）"
        print(f"{p['id']:<14}{len(rows):>3}  {brief}")

    print()
    for w in warns:
        print("  ⚠ " + w)
    if errs:
        print()
        for e in errs:
            print("  ✗ " + e)
        print(f"\n{len(errs)} 处要修（没写盘）")
        return 1
    print(f"体检通过：{len(CAST)} 卷人物表齐，性别证据全部对得上正文"
          + (f"，{len(warns)} 条复看项" if warns else ""))

    if not write:
        print("（只体检。要写回加 --write）")
        return 0
    changed = apply_cast(bundle)
    text = json.dumps(bundle, ensure_ascii=False, indent=2) + "\n"
    PUZZLES.write_text(text, encoding="utf-8")
    FUNCTIONS.write_text(text, encoding="utf-8")     # 部署前必须与根目录逐字节一致
    print(f"\n写了 {changed} 卷的 cast；puzzles.json 与 functions/puzzles.json 已同步")
    return 0


if __name__ == "__main__":
    sys.exit(main())
